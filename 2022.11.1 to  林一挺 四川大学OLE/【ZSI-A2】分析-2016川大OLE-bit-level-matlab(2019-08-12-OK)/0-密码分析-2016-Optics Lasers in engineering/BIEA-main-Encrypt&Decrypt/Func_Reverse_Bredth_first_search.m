function B=Func_Reverse_Bredth_first_search(A,num)
% B1=[1,2,5,3,6,9,4,7,10,13,8,11,14,12,15,16];
% B2=[4,3,8,2,7,12,1,6,11,16,5,10,15,9,14,13];
% B3=[13,14,9,15,10,5,16,11,6,1,12,7,2,8,3,4];
% B4=[16,15,12,14,11,8,13,10,7,4,9,6,3,5,2,1];
B1=[1,2,4,7,3,5,8,11,6,9,12,14,10,13,15,16];
B2=[7,4,2,1,11,8,5,3,14,12,9,6,16,15,13,10];
