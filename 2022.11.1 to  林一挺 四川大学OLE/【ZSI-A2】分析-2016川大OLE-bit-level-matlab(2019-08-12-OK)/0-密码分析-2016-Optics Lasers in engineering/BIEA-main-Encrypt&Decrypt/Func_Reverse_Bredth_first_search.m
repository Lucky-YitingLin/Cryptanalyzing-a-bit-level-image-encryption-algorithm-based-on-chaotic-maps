B4=[16,15,13,10,14,12,9,6,11,8,5,3,7,4,2,1];
switch num
    case 0
        for i=1:16
            B(i)=A(B1(i));
        end
    case 1
        for i=1:16
            B(i)=A(B2(i));
        end
    case 2
        for i=1:16
            B(i)=A(B3(i));
        end
    case 3
        for i=1:16
            B(i)=A(B4(i));
        end
end
end