%******************************************************************%
% 程序名称：Func_Cubic_Logistic(x0,u0,N0,len)
% 2019.3.9 by whp 
%******************************************************************%

function Out=Func_Cubic_Logistic(x0,u0,N0,len)
%********************初始值***************************
X(1)=x0; u=u0;
M=N0+len;
%********************Logistic&Tent-map************************
for k=1:M-1
    X(k+1)=u*X(k)*(1-X(k))*(2+X(k));
end
%****************************************************
Out=X(N0+1:N0+len);
end